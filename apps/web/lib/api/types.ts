export type WorkflowBooleanField =
  | "containsPii"
  | "isFirstMessage"
  | "isKnownContact"
  | "withinBusinessHours";

export type WorkflowConditionField = WorkflowTextField | WorkflowBooleanField;

export type WorkflowConditionOperator =
  | "equals"
  | "notEquals"
  | "contains"
  | "notContains"
  | "startsWith"
  | "endsWith"
  | "in"
  | "notIn"
  | "regex";

export interface WorkflowCondition {
  field: WorkflowConditionField;
  op: WorkflowConditionOperator;
  value: string | string[] | boolean;
}

export type WorkflowConditionNode =
  | WorkflowCondition
  | { all: WorkflowConditionNode[] }
  | { any: WorkflowConditionNode[] }
  | { not: WorkflowConditionNode };

/** A rule's conditions: one all/any/not group (groups nest). A rule that
 * should match every message says so with matchAll: true. */
export type WorkflowConditionGroup = (
  | { all: WorkflowConditionNode[] }
  | { any: WorkflowConditionNode[] }
  | { not: WorkflowConditionNode }
) & { matchAll?: boolean };

export type WorkflowAction =
  | {
      type: "AUTO_REPLY";
      agentId?: string;
      calendarAgent?: boolean;
      /** Copy everyone else on the original message. */
      replyAll?: boolean;
      /** Let replies grounded in your documents auto-send to senders
       * you've never corresponded with (default: held for review). */
      allowUnknownSenderGrounding?: boolean;
    }
  | { type: "ASSIGN_TO"; userId: string }
  | { type: "NOTIFY"; userId: string; message?: string }
  | {
      type: "POST_TO_SLACK";
      integrationId: string;
      channelId: string;
      message?: string;
    }
  | {
      type: "POST_TO_TEAMS";
      integrationId: string;
      teamId: string;
      channelId: string;
      message?: string;
    }
  | { type: "CREATE_HUBSPOT_CONTACT"; integrationId: string }
  | { type: "REQUIRE_APPROVAL" }
  | {
      type: "REQUIRE_APPROVAL_CHAIN";
      approverUserIds: string[];
      /** Pending chains expire after this many hours (default 72). */
      expiresInHours?: number;
    }
  | { type: "FORWARD"; to: string; note?: string }
  | { type: "ADD_LABEL"; label: string }
  | { type: "MOVE_TO_FOLDER"; folderId: string }
  | { type: "ARCHIVE" }
  | { type: "MARK_READ" }
  | { type: "SNOOZE"; minutes: number }
  | { type: "CREATE_TASK"; description?: string; dueInDays?: number }
  /** secret is generated by the server when the rule is saved. */
  | { type: "WEBHOOK"; url: string; secret?: string }
  | { type: "DELAY_SEND"; minutes: number }
  | { type: "STOP_PROCESSING" };

export type WorkflowActionType = WorkflowAction["type"];

